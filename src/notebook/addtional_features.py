def grad_cam_3d(model, volume, img_input_name='image_input', last_conv_name=None):
    """
    Compute Grad-CAM for the image branch. We assume model takes image input as first input.
    last_conv_name: name of last conv layer in the image encoder; if None, attempt heuristics.
    Returns heatmap of shape (z,y,x).
    """
    # Find image input index (first input assumed)
    img_input = model.inputs[0]
    # If model has multiple outputs, find last conv in base encoder via layer name hints
    if last_conv_name is None:
        # find last Conv3D in model
        convs = [l for l in model.layers if isinstance(l, layers.Conv3D)]
        if not convs:
            return None
        last_conv = convs[-1]
    else:
        last_conv = model.get_layer(last_conv_name)
    grad_model = tf.keras.models.Model([model.inputs[0]], [last_conv.output, model.output if isinstance(model.output, list) else model.output])
    with tf.GradientTape() as tape:
        conv_outputs, preds = grad_model(np.expand_dims(volume, axis=0))
        # if preds is list handle malignancy
        if isinstance(preds, list):
            score = preds[0][:,0]  # malignancy
        else:
            score = preds[:,0]
    grads = tape.gradient(score, conv_outputs)
    pooled_grads = tf.reduce_mean(grads, axis=(0,1,2,3))
    conv_outputs = conv_outputs[0]
    heatmap = tf.reduce_sum(tf.multiply(conv_outputs, pooled_grads), axis=-1)
    heatmap = np.maximum(heatmap, 0)
    heatmap = heatmap / (np.max(heatmap) + 1e-8)
    heatmap = heatmap.numpy()
    # resize heatmap to original volume shape if needed
    return heatmap

