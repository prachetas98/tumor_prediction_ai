# Radiomics AE stub (RadiomicsAE_256D_v1)
# -----------------------
def build_radiomics_ae(input_dim, latent_dim=256):
    inp = layers.Input(shape=(input_dim,), name='rad_input')
    x = layers.Dense(512, activation='relu')(inp)
    x = layers.Dense(384, activation='relu')(x)
    z = layers.Dense(latent_dim, activation='relu', name='rad_latent')(x)
    # decoder
    x = layers.Dense(384, activation='relu')(z)
    x = layers.Dense(512, activation='relu')(x)
    out = layers.Dense(input_dim, activation='linear')(x)
    ae = models.Model(inputs=inp, outputs=out, name='RadiomicsAE_256D_v1')
    encoder = models.Model(inputs=inp, outputs=z, name='RadiomicsAE_encoder')
    return ae, encoder

