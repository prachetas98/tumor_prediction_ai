def preprocess_clinical(df):
    """Select features, impute, encode categorical, scale numerics. Returns (X_df, encoders, scaler)."""
    df2 = df.copy()
    # choose a subset of clinical features (numeric + binary comorbidities + demographics)
    feature_cols = [
        'age_at_nephrectomy','body_mass_index','pack_years','hospitalization','ischemia_time',
        'radiographic_size','pathologic_size','tumor_isup_grade','clavien_surgical_complications',
        'estimated_blood_loss'
    ]
    # add binary comorbidity columns if present
    comorbidity_cols = [c for c in df2.columns if c.startswith('comorbidities__')]
    # gender
    if 'gender' in df2.columns:
        feature_cols.append('gender')
    feature_cols += [c for c in comorbidity_cols]
    # ensure columns exist
    feature_cols = [c for c in feature_cols if c in df2.columns]
    X = df2[feature_cols].copy()
    # Impute numeric with median, categorical with mode
    for c in X.columns:
        if X[c].dtype in [np.float64, np.float32, np.int64, np.int32]:
            X[c] = X[c].fillna(X[c].median())
        else:
            X[c] = X[c].fillna(X[c].mode().iloc[0] if not X[c].mode().empty else 0)
    # encode gender if exists
    encoders = {}
    if 'gender' in X.columns:
        le_g = LabelEncoder()
        X['gender'] = le_g.fit_transform(X['gender'].astype(str))
        encoders['gender'] = le_g
    # binary comorbidities likely 0/1 already; ensure numeric
    for c in comorbidity_cols:
        if c in X.columns:
            X[c] = pd.to_numeric(X[c], errors='coerce').fillna(0).astype(int)
    # scale numeric features
    numeric_cols = X.select_dtypes(include=[np.number]).columns.tolist()
    scaler = StandardScaler()
    X[numeric_cols] = scaler.fit_transform(X[numeric_cols])
    return X, encoders, scaler, feature_cols

