# === Added Section: 3D UNet + LoRA encoder (CNN3D_UNet_LoRA_v1) ===
# -----------------------
def conv3d_block(inputs, filters, kernel=(3,3,3), padding='same', name=None):
    x = layers.Conv3D(filters, kernel, padding=padding, kernel_initializer='he_normal')(inputs)
    x = layers.BatchNormalization()(x)
    x = layers.Activation('relu')(x)
    # add LoRA adapter with small rank
    x = lora_conv3d(x, filters, kernel_size=(1,1,1), rank=max(1, filters//16), alpha=0.5, name=name)
    return x

def build_unet3d_lora(input_shape=(64,128,128,1), base_filters=16, depth=3):
    """
    Build a compact 3D UNet encoder with LoRA adapters.
    Returns: Keras Model that outputs a feature vector after GlobalAveragePooling.
    """
    inp = layers.Input(shape=input_shape, name='image_input')
    skips = []
    x = inp
    # encoder
    for d in range(depth):
        f = base_filters * (2**d)
        x = conv3d_block(x, f, name=f'enc{d}_a')
        x = conv3d_block(x, f, name=f'enc{d}_b')
        skips.append(x)
        x = layers.MaxPooling3D((2,2,2), name=f'enc{d}_pool')(x)
    # bottleneck
    f = base_filters * (2**depth)
    x = conv3d_block(x, f, name='bottleneck_a')
    x = conv3d_block(x, f, name='bottleneck_b')
    # global features
    gap = layers.GlobalAveragePooling3D(name='gap3d')(x)
    dense = layers.Dense(128, activation='relu', name='image_dense')(gap)
    image_encoder = models.Model(inputs=inp, outputs=dense, name='CNN3D_UNet_LoRA_v1_encoder')
    return image_encoder

