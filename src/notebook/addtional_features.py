def discover_patient_folders(image_root):
    """Return list of patient subfolders under image_root (e.g., KiTS-00000...)"""
    if not image_root.exists():
        # try find directory under RAW_DIR
        dirs = [d for d in RAW_DIR.iterdir() if d.is_dir()]
        if not dirs:
            return []
        # return deepest directories that look like KiTS-*
        candidate = None
        for d in dirs:
            if any(re.match(r'KiTS-\d+', c.name) for c in d.iterdir() if c.is_dir()):
                candidate = d
                break
        if candidate:
            image_root = candidate
        else:
            image_root = dirs[0]
    patients = [p for p in image_root.iterdir() if p.is_dir()]
    return sorted(patients)

def build_dataset_from_raw(max_patients=None, target_shape=(64,128,128)):
    """Build arrays: images (N, z,y,x,1), clinical matrix (N, F), labels dict."""
    patient_dirs = discover_patient_folders(IMAGE_ROOT)
    if max_patients:
        patient_dirs = patient_dirs[:max_patients]
    images = []
    clin_rows = []
    labels = []
    subtype_labels = []
    kidney_declines = []
    surv_times = []
    surv_events = []
    for p in patient_dirs:
        pid = p.name  # sometimes KiTS-00000; try to match to patient_id in clinical_df
        # attempt match by patient_id numeric if clinical stores numeric suffix
        # Try different candidate id formats from metadata or folder name
        # We'll attempt to find a row in clinical_df by searching patient_id substring
        # (You may adapt this mapping to your metadata)
        possible = clinical_df[clinical_df[CLINICAL_ID_COL].astype(str).str.contains(p.name)]
        if possible.empty:
            # try by number part
            digits = re.findall(r'\d+', p.name)
            if digits:
                candidate = clinical_df[clinical_df[CLINICAL_ID_COL].astype(str).str.contains(digits[0])]
                if not candidate.empty:
                    row = candidate.iloc[0]
                else:
                    # fallback: skip
                    continue
            else:
                continue
        else:
            row = possible.iloc[0]
        vol = read_dicom_volume(p)
        if vol is None:
            continue
        # Preprocess volume: hu clip -> normalize -> CLAHE -> resize -> channel axis
        vol = hu_clip_and_normalize(vol)
        vol = clahe_volume(vol)
        vol = resize_volume(vol, target_shape)
        vol = np.expand_dims(vol, axis=-1)  # z,y,x,1
        images.append(vol)
        clin_rows.append(row)
        # targets & derived
        labels.append(int(row.get(TARGET_MALIGNANT, 0)))
        subtype_labels.append(row.get(TARGET_SUBTYPE, 'UNK'))
        pre = row.get(EGFR_PRE_COL, np.nan)
        post = row.get(EGFR_POST_COL, np.nan)
        if pd.isna(pre) or pd.isna(post):
            kidney_declines.append(np.nan)
        else:
            kidney_declines.append(float(pre) - float(post))  # decline = pre - post
        surv_times.append(row.get(SURV_TIME_COL, np.nan))
        # convert vital_status -> event (1=dead, 0=alive) heuristic
        vs = row.get(SURV_STATUS_COL, '')
        ev = 1 if str(vs).strip().lower() not in ('alive', '0', '', 'nan', 'none') else 0
        surv_events.append(ev)
    if not images:
        raise RuntimeError("No patient images found. Check image folders.")
    images = np.stack(images, axis=0).astype(np.float32)  # N,z,y,x,1
    clinical = pd.DataFrame(clin_rows).reset_index(drop=True)
    labels = np.array(labels, dtype=np.int32)
    subtype_labels = np.array(subtype_labels)
    kidney_declines = np.array(kidney_declines, dtype=np.float32)
    surv_times = np.array(surv_times, dtype=np.float32)
    surv_events = np.array(surv_events, dtype=np.int32)
    return images, clinical, labels, subtype_labels, kidney_declines, surv_times, surv_events

