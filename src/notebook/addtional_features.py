def augment_volume(volume):
    """Simple on-the-fly augmentation: flips, small rotations, intensity jitter"""
    v = volume.copy()
    # random flip
    if random.random() < 0.5:
        v = v[:, ::-1, :]  # flip y
    if random.random() < 0.5:
        v = v[:, :, ::-1]  # flip x
    # small rotation about z (in-plane)
    if random.random() < 0.3:
        angle = random.uniform(-10,10)
        for i in range(v.shape[0]):
            v[i] = cv2.warpAffine(v[i], cv2.getRotationMatrix2D((v.shape[2]/2, v.shape[1]/2), angle, 1.0),
                                  (v.shape[2], v.shape[1]), flags=cv2.INTER_LINEAR, borderMode=cv2.BORDER_REFLECT)
    # intensity noise
    if random.random() < 0.3:
        v += np.random.normal(0, 0.01, v.shape)
        v = np.clip(v, 0.0, 1.0)
    return v

