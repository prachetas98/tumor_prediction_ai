def simple_generator(images, clinical_mat, labels, batch_size=4, shuffle=True, augment=False):
    """Yields batches of (img, clin), y."""
    N = images.shape[0]
    idxs = np.arange(N)
    while True:
        if shuffle:
            np.random.shuffle(idxs)
        for start in range(0, N, batch_size):
            batch_idx = idxs[start:start+batch_size]
            imgs = images[batch_idx].astype(np.float32)
            if augment:
                imgs = np.stack([augment_volume(im.squeeze()) for im in imgs], axis=0)[..., None]
            clins = clinical_mat.values[batch_idx].astype(np.float32)
            ys = labels[batch_idx].astype(np.float32)
            yield [imgs, clins], ys

