def read_dicom_volume(folder):
    """
    Read DICOM slices from a folder and return a (z, y, x) numpy array.
    Automatically skips or reshapes inconsistent slices.
    """
    files = sorted(glob(str(Path(folder) / '**' / '*.dcm'), recursive=True))
    if not files:
        # fallback to PNG/JPG
        imgs = sorted(glob(str(Path(folder) / '**' / '*.png'), recursive=True)) + \
               sorted(glob(str(Path(folder) / '**' / '*.jpg'), recursive=True))
        if not imgs:
            return None
        arrs = [iio.imread(p) for p in imgs]
        shapes = [a.shape for a in arrs]
        # enforce consistent shape
        common_shape = Counter(shapes).most_common(1)[0][0]
        arrs = [cv2.resize(a, (common_shape[1], common_shape[0])) if a.shape != common_shape else a for a in arrs]
        return np.stack(arrs, axis=0).astype(np.float32)

    slices = []
    for p in files:
        try:
            ds = pydicom.dcmread(p)
            arr = ds.pixel_array.astype(np.float32)

            # handle accidental 3D arrays in one file
            if arr.ndim == 3:
                for i in range(arr.shape[0]):
                    slices.append((float(getattr(ds, 'InstanceNumber', i)), arr[i]))
                continue

            intercept = float(getattr(ds, 'RescaleIntercept', 0.0))
            slope = float(getattr(ds, 'RescaleSlope', 1.0))
            arr = arr * slope + intercept
            slices.append((float(getattr(ds, 'InstanceNumber', len(slices))), arr))
        except Exception as e:
            print(f"Warning: could not read {p}: {e}")
            continue

    if not slices:
        return None

    # --- NEW: enforce consistent shape ---
    slice_arrays = [s[1] for s in slices]
    shapes = [a.shape for a in slice_arrays]
    most_common_shape = Counter(shapes).most_common(1)[0][0]
    # resize inconsistent slices
    normalized_slices = []
    for arr in slice_arrays:
        if arr.shape != most_common_shape:
            arr = cv2.resize(arr, (most_common_shape[1], most_common_shape[0]), interpolation=cv2.INTER_LINEAR)
        normalized_slices.append(arr)

    vol = np.stack(normalized_slices, axis=0).astype(np.float32)
    return vol

def hu_clip_and_normalize(volume, min_hu=-1000, max_hu=400):
    """Clip HU and normalize to 0..1"""
    v = np.clip(volume, min_hu, max_hu)
    v = (v - min_hu) / (max_hu - min_hu)
    return v.astype(np.float32)

def clahe_volume(volume):
    """Apply CLAHE (per-slice) to enhance contrast. volume shape (z,y,x)"""
    out = np.zeros_like(volume, dtype=np.float32)
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8,8))
    for i in range(volume.shape[0]):
        # Convert to uint8 temporarily for CLAHE
        slice_img = np.uint8(np.clip(volume[i]*255.0, 0, 255))
        out_slice = clahe.apply(slice_img)
        out[i] = out_slice.astype(np.float32) / 255.0
    return out

def resize_volume(volume, target_shape=(64,128,128)):
    """Resize volume (z,y,x) to target (z,y,x) using cv2.resize per-slice for x,y and simple interp for z."""
    z, y, x = volume.shape
    tz, ty, tx = target_shape
    # resize x,y per slice
    vol_xy = np.zeros((z, ty, tx), dtype=np.float32)
    for i in range(z):
        vol_xy[i] = cv2.resize(volume[i], (tx, ty), interpolation=cv2.INTER_LINEAR)
    # now resize in z axis
    if z != tz:
        indices = np.linspace(0, z-1, tz).astype(np.float32)
        vol_z = np.zeros((tz, ty, tx), dtype=np.float32)
        for i, idx in enumerate(indices):
            lo = int(math.floor(idx))
            hi = min(lo+1, z-1)
            alpha = idx - lo
            vol_z[i] = (1-alpha) * vol_xy[lo] + alpha * vol_xy[hi]
        return vol_z
    return vol_xy

