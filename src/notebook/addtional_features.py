# Fusion multi-task model (FusionMultiTask_Enc_v1)
# -----------------------
def build_fusion_model(image_encoder, clinical_encoder, radiomics_encoder=None, multitask=True):
    """
    Fuse image features + clinical features (+ optional radiomics features) and produce multitask outputs.
    """
    img_in = image_encoder.input
    clin_in = clinical_encoder.input
    img_feat = image_encoder.output
    clin_feat = clinical_encoder.output
    concat = layers.Concatenate(name='fusion')([img_feat, clin_feat])
    if radiomics_encoder is not None:
        rad_in = radiomics_encoder.input
        rad_feat = radiomics_encoder.output
        concat = layers.Concatenate(name='fusion_with_rad')([concat, rad_feat])
        inputs = [img_in, clin_in, rad_in]
    else:
        inputs = [img_in, clin_in]

    x = layers.Dense(128, activation='relu')(concat)
    x = layers.Dropout(0.3)(x)
    x = layers.Dense(64, activation='relu')(x)
    # outputs
    out_malign = layers.Dense(1, activation='sigmoid', name='out_malignancy')(x)
    if not multitask:
        model = models.Model(inputs=inputs, outputs=out_malign, name='FusionSingle_malig')
        model.compile(optimizer=tf.keras.optimizers.Adam(1e-4),
                      loss={'out_malignancy':'binary_crossentropy'},
                      metrics={'out_malignancy':['accuracy']})
        return model

    # multitask heads:
    out_subtype = layers.Dense(8, activation='softmax', name='out_subtype')(x)        # tune number of classes
    out_kidney = layers.Dense(1, activation='linear', name='out_kidney_decline')(x)    # regression
    out_surv = layers.Dense(1, activation='linear', name='out_survival')(x)
    model = models.Model(inputs=inputs, outputs=[out_malign, out_subtype, out_kidney, out_surv], name='FusionMultiTask_Enc_v1')
    losses = {
        'out_malignancy':'binary_crossentropy',
        'out_subtype':'sparse_categorical_crossentropy',
        'out_kidney_decline':'mse',
        'out_survival':'mse'
    }
    metrics = {
        'out_malignancy':['accuracy'],
        'out_subtype':['accuracy'],
        'out_kidney_decline':['mse'],
        'out_survival':['mse']
    }
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-4), loss=losses, metrics=metrics)
    return model

