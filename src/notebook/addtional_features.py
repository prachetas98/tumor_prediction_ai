def lora_conv3d(x, filters, kernel_size=(1,1,1), rank=4, alpha=1.0, name=None):
    """
    Implement a LoRA adapter for Conv3D by adding a low-rank residual branch:
    y = x + alpha * (U(V(x))) where U and V are Conv3D with rank channels.
    This is a lightweight adapter added in parallel to a Conv3D layer in the UNet encoder.
    """
    v = layers.Conv3D(rank, kernel_size=kernel_size, padding='same', use_bias=False,
                      kernel_initializer='he_normal', name=(None if not name else name + '_V'))(x)
    u = layers.Conv3D(filters, kernel_size=(1,1,1), padding='same', use_bias=False,
                      kernel_initializer='zeros', name=(None if not name else name + '_U'))(v)
    if alpha != 1.0:
        u = layers.Lambda(lambda t: t * alpha)(u)
    return layers.Add()([x, u])

