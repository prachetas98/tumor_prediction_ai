def build_clinical_encoder(input_dim, name='ClinicalDense_4x128_v2'):
    inp = layers.Input(shape=(input_dim,), name='clin_input')
    x = inp
    x = layers.Dense(128, activation='relu')(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dense(128, activation='relu')(x)
    x = layers.Dropout(0.2)(x)
    x = layers.Dense(64, activation='relu')(x)
    out = layers.Dense(32, activation='relu', name='clin_features')(x)
    model = models.Model(inputs=inp, outputs=out, name=name)
    return model

